"""Smoke test: Gnani Prisma speech-to-text (REST).

Transcribes an audio file (default: out/hello.wav generated by smoke_timbre.py).
Proves the API key, credits, and STT endpoint shape.

Usage:
    python scripts/smoke_prisma.py [--file out/hello.wav] [--language hi-IN]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from remo.config import load_settings
from remo.log import get_logger
from remo.stt import transcribe_file_rest

log = get_logger("smoke_prisma")


def main() -> int:
    parser = argparse.ArgumentParser(description="Transcribe audio via Gnani Prisma.")
    parser.add_argument("--file", default="out/hello.wav", help="Audio file (<=30s).")
    parser.add_argument("--language", default=None, help="e.g. hi-IN (default from config).")
    args = parser.parse_args()

    audio_path = Path(args.file)
    if not audio_path.exists():
        log.error("Missing %s. Run scripts/smoke_timbre.py first to generate it.", audio_path)
        return 2

    settings = load_settings()
    try:
        transcript = transcribe_file_rest(audio_path, args.language or settings.language)
    except Exception as exc:  # noqa: BLE001 - smoke script reports and exits nonzero
        log.error("Prisma smoke test FAILED: %s", exc)
        return 1
    log.info("Prisma smoke test PASSED. Transcript: %s", transcript or "(empty)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
